# Pre-build hook for the About page (issue #13):
#   FW_VERSION  the git revision this firmware was built from ("cbcb613", "cbcb613-dirty", or "unknown")
#   about_credits.h  the credit lines between the about:begin/about:end markers in CREDITS.md,
#                    so the page and CREDITS.md cannot drift apart. Written into the build dir.
Import("env")
import os, subprocess

proj = env.subst("$PROJECT_DIR")
root = os.path.abspath(os.path.join(proj, ".."))

try:
    # --match=NOTHING: never describe from a tag, always the bare short hash (+ "-dirty" if edited)
    ver = subprocess.check_output(["git", "describe", "--always", "--dirty", "--abbrev=7", "--match=NOTHING"],
                                  cwd=root, stderr=subprocess.DEVNULL).decode().strip() or "unknown"
except Exception:
    ver = "unknown"
env.Append(CPPDEFINES=[("FW_VERSION", env.StringifyMacro(ver))])

lines, inside = [], False
for raw in open(os.path.join(root, "CREDITS.md"), encoding="utf-8").read().splitlines():
    t = raw.strip()
    if t == "<!-- about:begin -->": inside = True; continue
    if t == "<!-- about:end -->": inside = False; continue
    if inside and t and not t.startswith("```"): lines.append(t)
if not lines:
    raise RuntimeError("CREDITS.md has no about:begin / about:end block (the About page credits come from it)")

gen = os.path.join(env.subst("$BUILD_DIR"), "gen")
os.makedirs(gen, exist_ok=True)
with open(os.path.join(gen, "about_credits.h"), "w", encoding="ascii", errors="replace") as f:
    f.write("// GENERATED by about_pre.py from CREDITS.md - do not edit.\n#pragma once\n")
    f.write("static const char* const ABOUT_CREDITS[] = {\n")
    for l in lines:
        f.write('  "%s",\n' % l.encode("ascii", "replace").decode().replace("\\", "/").replace('"', "'"))
    f.write("};\n#define ABOUT_CREDITS_N %d\n" % len(lines))
env.Append(CPPPATH=[gen])
print("[about] FW_VERSION=%s, %d credit lines" % (ver, len(lines)))
